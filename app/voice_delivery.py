def with_voice_delivery(base: str) -> str:
    """Keep the shared persona and add the v4 audio-tag contract after it.

    The shared prompt forbids markdown. These square-bracket tags are the
    exception Eleven v4 reads as delivery, so that ban does not cover them.
    """
    adjusted = base.replace(
        "마크다운 표기는 사용하지 마세요.",
        "마크다운 표기는 사용하지 마세요. 아래 voice_delivery의 오디오 태그만 예외입니다.",
    )
    return f"{adjusted.rstrip()}\n\n{VOICE_DELIVERY}"


def wants_voice_delivery(body: dict, path: str) -> bool:
    if path.rstrip("/").startswith("/v4"):
        return True
    extra = body.get("elevenlabs_extra_body")
    return isinstance(extra, dict) and extra.get("voice_delivery") is True
